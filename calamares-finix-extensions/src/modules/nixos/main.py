def _noctalia_session_nix(comp):
    """One '<compositor> + Noctalia' launcher: start the compositor, wait for
    its Wayland socket, then start audio + Noctalia next to it. Generic on
    purpose — works the same for labwc, niri and mango, and never touches the
    compositor's own config files."""
    c = _NOCTALIA_COMPOSITORS[comp]
    # Noctalia's logout button talks to niri through its IPC socket, found
    # ONLY via $NIRI_SOCKET — and noctalia is started as the compositor's
    # sibling here, so it never inherits it. Export it explicitly (the
    # socket name embeds the compositor pid: niri.<display>.<pid>.sock).
    niri_socket = ""
    if comp == "niri":
        niri_socket = (
            '      i=0\n'
            '      while [ $i -lt 20 ]; do\n'
            '        for ns in "$XDG_RUNTIME_DIR"/niri.*.sock; do\n'
            '          if [ -S "$ns" ]; then export NIRI_SOCKET="$ns"; break 2; fi\n'
            '        done\n'
            '        i=$((i + 1))\n'
            '        sleep 0.1\n'
            '      done\n'
        )
    script = (
        '  session-' + comp + '-noctalia = pkgs.writeShellScript "session-' + comp + '-noctalia" \'\'\n'
        '    ' + c["cmd"] + ' &\n'
        '    comp=$!\n'
        '    sock=""\n'
        '    i=0\n'
        '    while [ $i -lt 100 ]; do\n'
        '      for s in "$XDG_RUNTIME_DIR"/wayland-*; do\n'
        '        case "$s" in\n'
        '          *.lock) ;;\n'
        '          *) if [ -S "$s" ]; then sock="$(basename "$s")"; break; fi ;;\n'
        '        esac\n'
        '      done\n'
        '      [ -n "$sock" ] && break\n'
        '      i=$((i + 1))\n'
        '      sleep 0.1\n'
        '    done\n'
        '    if [ -n "$sock" ]; then\n'
        '      export WAYLAND_DISPLAY="$sock"\n'
        '      # first XWayland display on a fresh boot\n'
        '      export DISPLAY=:0\n'
        + niri_socket +
        '      ${audioStart}\n'
        '      ${noctalia}/bin/noctalia --daemon &\n'
        '    fi\n'
        '    wait "$comp"\n'
        '  \'\';\n'
    )
    desktop = (
        '    (pkgs.writeTextDir "share/wayland-sessions/' + comp + '-noctalia.desktop" \'\'\n'
        '      [Desktop Entry]\n'
        '      Name=' + c["name"] + ' + Noctalia\n'
        '      Comment=' + c["comment"] + '\n'
        '      Exec=${pkgs.dbus}/bin/dbus-run-session -- ${session-' + comp + '-noctalia}\n'
        '      Type=Application\n'
        '      DesktopNames=' + c["desktop_names"] + '\n'
        '    \'\')\n'
    )
    return script, desktop


