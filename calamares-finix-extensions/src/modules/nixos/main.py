def catenate(d, key, *values):
    """
    Sets @p d[key] to the string-concatenation of @p values
    if none of the values are None.
    This can be used to set keys conditionally based on
    the values being found.
    """
    if [v for v in values if v is None]:
        return

    d[key] = "".join(values)


def fix_btrfs_subvolumes(hardware_config, partitions):
    """
    Fix btrfs subvolume configuration in hardware-configuration.nix.

    nixos-generate-config generates incorrect subvol options for btrfs
    by setting them to mount points instead of actual subvolume names.
    This function corrects the subvol options to match what Calamares configured.
    """
    # Map of mount points to their correct btrfs subvolume names
    # These match what is configured in mount.conf btrfsSubvolumes
    # Root uses top-level (no subvolume) for GRUB compatibility
    subvol_map = {
        "/home": "home",
        "/nix": "nix",
    }

    # Check if root is actually btrfs
    root_is_btrfs = False
    for part in partitions:
        if part.get("mountPoint") == "/" and part.get("fs") == "btrfs":
            root_is_btrfs = True
            break

    if not root_is_btrfs:
        return hardware_config

    libcalamares.utils.debug("Fixing btrfs subvolume configuration")

    # Fix subvol options for each mount point
    # nixos-generate-config may generate "subvol=/" instead of "subvol=@"
    for mount_point, correct_subvol in subvol_map.items():
        # Match any "subvol=<something>" and replace with correct subvolume
        # This handles cases like "subvol=/" or "subvol=/home"
        pattern = r'(fileSystems\."{}"[^;]*"subvol=)[^"]*"'.format(re.escape(mount_point))
        replacement = r'\g<1>{}"'.format(correct_subvol)
        hardware_config = re.sub(pattern, replacement, hardware_config, flags=re.DOTALL)

    return hardware_config


_FINIX_HW_KEEP_PREFIXES = (
    "boot.initrd.availableKernelModules",
    "boot.initrd.kernelModules",
    "boot.kernelModules",
    "boot.extraModulePackages",
    "fileSystems.",
    "fileSystems",
    "swapDevices",
)


def _finix_split_top_level(body):
    """Split a Nix attrset body into top-level statements (terminated by ';'
    at bracket depth 0). Tracks (){}[] depth and skips '#' line comments so
    that ';' inside nested blocks or comments does not split a statement."""
    stmts = []
    buf = []
    depth = 0
    in_comment = False
    for c in body:
        if in_comment:
            buf.append(c)
            if c == "\n":
                in_comment = False
            continue
        if c == "#":
            in_comment = True
            buf.append(c)
            continue
        if c in "[{(":
            depth += 1
        elif c in "]})":
            depth -= 1
        buf.append(c)
        if c == ";" and depth == 0:
            stmts.append("".join(buf))
            buf = []
    tail = "".join(buf)
    return stmts, tail


def _finix_stmt_key(stmt):
    """Return the bare left-hand-side attribute path of a Nix statement,
    with leading comments/whitespace stripped (e.g. 'boot.kernelModules')."""
    lhs = stmt.split("=", 1)[0]
    lhs = "\n".join(line.split("#", 1)[0] for line in lhs.splitlines())
    return lhs.strip()


def finixify_hardware_config(hardware_config):
    """
    Strip NixOS-only options from nixos-generate-config output so the generated
    hardware-configuration.nix evaluates against Finix's (much smaller) module
    set. Finix does not define hardware.enableRedistributableFirmware (pulled in
    via the not-detected.nix import), hardware.cpu.*.updateMicrocode,
    networking.useDHCP, nixpkgs.hostPlatform, powerManagement.*, etc. Per the
    upstream Finix install docs, the file must be reduced to boot.initrd.*,
    boot.kernelModules, boot.extraModulePackages, fileSystems.*, swapDevices,
    plus an explicit hardware.firmware = [ pkgs.linux-firmware ] for wireless/GPU
    firmware. Uses a keep-list so any future NixOS-only addition is dropped too.
    """
    # Split off the function-argument header: the ':' after the first balanced
    # { ... } (the argument attrset).
    first_open = hardware_config.find("{")
    if first_open == -1:
        return hardware_config
    depth = 0
    i = first_open
    while i < len(hardware_config):
        ch = hardware_config[i]
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                break
        i += 1
    colon = hardware_config.find(":", i)
    if colon == -1:
        return hardware_config
    header = hardware_config[: colon + 1]

    # Locate the body attrset that follows the header.
    rest = hardware_config[colon + 1 :]
    body_open = rest.find("{")
    if body_open == -1:
        return hardware_config
    depth = 0
    j = body_open
    while j < len(rest):
        ch = rest[j]
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                break
        j += 1
    body = rest[body_open + 1 : j]

    stmts, _tail = _finix_split_top_level(body)
    kept = []
    for stmt in stmts:
        key = _finix_stmt_key(stmt)
        if any(key == p or key.startswith(p) for p in _FINIX_HW_KEEP_PREFIXES):
            kept.append(stmt)

    new_body = "".join(kept).rstrip()
    return (
        header
        + "\n\n{\n"
        + new_body
        # linux-firmware = wifi/bt/gpu blobs; sof-firmware = audio DSP on
        # modern (2019+) Intel laptops — on NixOS both come via
        # hardware.enableRedistributableFirmware, which finix doesn't have.
        + "\n\n  hardware.firmware = [\n    pkgs.linux-firmware\n    pkgs.sof-firmware\n  ];\n}\n"
    )


# The by-uuid paths emitted by nixos-generate-config are kept as-is, which is
# independent of device enumeration order (it can differ between the live ISO
# and the installed kernel on machines with several disks). This relies on the
# pinned Finix revision's mdevd module, which ships mdevd-disk.sh (blkid-driven)
# in both the system and the initrd to create /dev/disk/by-uuid at coldplug,
# with the initrd's wait-dev task polling the path for up to 90s. See finix
# issue #67 for the history.


# nix internal-json activity/result types
_ACT_COPY_PATH = 100
_ACT_COPY_PATHS = 103
_ACT_BUILDS = 104
_RES_PROGRESS = 105


class NixProgress:
    """Parse nix internal-json output and track build/copy progress."""

    def __init__(self):
        self._builds_done = 0
        self._builds_expected = 0
        self._copies_done = 0
        self._copies_expected = 0
        self._per_act_progress = {}
        self._copy_bytes = {}
        self._activities = {}
        self.fraction = 0.0
        self._floor = 0.0
        self._floor_done = 0
        self.log_messages = []

    def handle(self, line):
        """Process one line. Returns True for @nix lines, False for plain text."""
        line = line.strip()
        if not line:
            return True
        if not line.startswith("@nix "):
            return False
        try:
            msg = json.loads(line[5:])
        except (json.JSONDecodeError, ValueError):
            return False

        action = msg.get("action")
        if action == "start":
            self._on_start(msg)
        elif action == "stop":
            self._on_stop(msg)
        elif action == "result":
            self._on_result(msg)
        elif action == "msg":
            level = msg.get("level", 0)
            text = msg.get("msg", "")
            if level <= 1 and text:
                self.log_messages.append(text)

        self._update()
        return True

    def _on_start(self, msg):
        act_id = msg["id"]
        act_type = msg.get("type", 0)
        self._activities[act_id] = act_type
        text = msg.get("text", "")
        if text and msg.get("level", 5) <= 3:
            self.log_messages.append(text)

    def _on_stop(self, msg):
        act_id = msg["id"]
        self._activities.pop(act_id, None)
        self._copy_bytes.pop(act_id, None)

    def _on_result(self, msg):
        act_id = msg["id"]
        res_type = msg.get("type", 0)
        fields = msg.get("fields", [])
        act_type = self._activities.get(act_id, 0)

        if res_type != _RES_PROGRESS or len(fields) < 2:
            return
        if act_type == _ACT_BUILDS:
            self._per_act_progress[(act_type, act_id)] = (
                "builds",
                fields[0],
                fields[1],
            )
            self._recompute_counts()
        elif act_type == _ACT_COPY_PATHS:
            self._per_act_progress[(act_type, act_id)] = (
                "copies",
                fields[0],
                fields[1],
            )
            self._recompute_counts()
        elif act_type == _ACT_COPY_PATH:
            self._copy_bytes[act_id] = (fields[0], max(fields[1], 1))

    def _update(self):
        count_total = self._builds_expected + self._copies_expected
        count_done = self._builds_done + self._copies_done
        if count_total <= 0:
            return

        # Prevents the channel copy (1 path) from dominating the
        # entire progress bar before the main build starts.
        effective_total = max(count_total, 3)
        count_frac = count_done / effective_total

        # large single-path copies move the bar.
        total_bytes = sum(t for _, t in self._copy_bytes.values())
        done_bytes = sum(d for d, _ in self._copy_bytes.values())
        if total_bytes > 0:
            byte_sub = done_bytes / total_bytes
            step = len(self._copy_bytes) / effective_total
            raw = count_frac + byte_sub * step
        else:
            raw = count_frac
        raw = max(0.0, min(1.0, raw))

        # When the denominator grows (e.g. main build discovers hundreds
        # of new paths), remap remaining work into remaining bar space.
        if raw >= self._floor:
            self._floor = raw
            self._floor_done = count_done
        else:
            new_items = count_done - self._floor_done
            remaining = effective_total - self._floor_done
            if remaining > 0 and new_items >= 0:
                raw = self._floor + (new_items / remaining) * (1.0 - self._floor)
            else:
                raw = self._floor
            raw = max(0.0, min(1.0, raw))
            if raw > self._floor:
                self._floor = raw
                self._floor_done = count_done

        self.fraction = raw

    def _recompute_counts(self):
        bd = be = cd = ce = 0
        for kind, done, expected in self._per_act_progress.values():
            if kind == "builds":
                bd += done
                be += expected
            else:
                cd += done
                ce += expected
        self._builds_done = bd
        self._builds_expected = be
        self._copies_done = cd
        self._copies_expected = ce


def run():
    """Finix Configuration."""

    INSTALL_PROGRESS_START = 0.1
    INSTALL_PROGRESS_END = 1.0

    global status
    status = _("Configuring Finix")
    libcalamares.job.setprogress(0.01)

    ngc_cfg = configparser.ConfigParser()
    ngc_cfg["Defaults"] = { "Kernel": "lts" }
    ngc_cfg.read("/etc/nixos-generate-config.conf")

    # Create initial config file
    cfg = cfghead
    gs = libcalamares.globalstorage
    variables = dict()

    # Setup variables
    root_mount_point = gs.value("rootMountPoint")
    # Finix keeps its system flake in /etc/finix (not /etc/nixos).
    config = os.path.join(root_mount_point, "etc/finix/configuration.nix")
    fw_type = gs.value("firmwareType")
    bootdev = (
        "nodev"
        if gs.value("bootLoader") is None
        else gs.value("bootLoader")["installPath"]
    )

    # Pick config parts and prepare substitution

    # Check if root filesystem is btrfs
    root_is_btrfs = False
    for part in gs.value("partitions"):
        if part.get("mountPoint") == "/" and part.get("fs") == "btrfs":
            root_is_btrfs = True
            break

    # Check bootloader
    if fw_type == "efi":
        cfg += cfgbootefi
    elif bootdev != "nodev":
        # Use btrfs-specific config to avoid blkid issues with subvolumes
        if root_is_btrfs:
            cfg += cfgbootbiosbtrfs
        else:
            cfg += cfgbootbios
        catenate(variables, "bootdev", bootdev)
    else:
        cfg += cfgbootnone

    if ngc_cfg["Defaults"]["Kernel"] == "latest":
        cfg += cfglatestkernel

    # Finix has no boot.initrd.luks.devices option (its LUKS support is the
    # separate boot.initrd.supportedFilesystems.luks mechanism, untested with
    # this installer). Emitting the NixOS option would abort the install with
    # "option does not exist", so LUKS setups are not emitted; warn instead.
    for part in gs.value("partitions"):
        if (
            part["claimed"] is True
            and (part["fsName"] == "luks" or part["fsName"] == "luks2")
        ):
            libcalamares.utils.warning(
                "LUKS partition {} detected: encrypted installs are not "
                "supported by the Finix installer yet; skipping initrd LUKS "
                "config for it".format(part.get("device"))
            )

    # Check partitions
    root_is_encrypted = False
    boot_is_encrypted = False
    boot_is_partition = False

    for part in gs.value("partitions"):
        if part["mountPoint"] == "/":
            root_is_encrypted = part["fsName"] in ["luks", "luks2"]
        elif part["mountPoint"] == "/boot":
            boot_is_partition = True
            boot_is_encrypted = part["fsName"] in ["luks", "luks2"]

    # The BIOS/GRUB crypto_keyfile flow was removed: it emitted
    # boot.initrd.luks.devices.*.keyFile, which does not exist on Finix
    # (see the LUKS warning above; Finix is UEFI/limine anyway).

    status = _("Configuring Finix")
    libcalamares.job.setprogress(0.03)

    # Desktop / compositor selection (multi-select packagechooser: the value
    # is a comma-separated list of ids).
    selected, needs = parse_desktop_selection(
        gs.value("packagechooser_packagechooser") or "",
        warn=libcalamares.utils.warning,
    )

    # Cap per-build compiler parallelism by available RAM. Each C++/Rust
    # compile job peaks around 1.5-2 GB; on an 8 GB machine 8 parallel jobs
    # inside one derivation can freeze the system even with --max-jobs 1.
    # Used for the install itself AND written into the installed system's
    # config so post-update rebuilds stay safe on the same hardware.
    build_cores = 0  # 0 = nix default (all cores)
    try:
        mem_gb = 0
        with open("/proc/meminfo") as f:
            for line in f:
                if line.startswith("MemTotal:"):
                    mem_gb = int(line.split()[1]) // (1024 * 1024)
                    break
        cpus = os.cpu_count() or 4
        if mem_gb and mem_gb < 20:
            # ~1 compile job per 2 GB of RAM (8 GB -> 4 jobs). Safe now that
            # builds are serialized, scratch lives on the target disk and the
            # target's swap is enabled during the install.
            build_cores = max(1, min(cpus, mem_gb // 2))
    except Exception as e:
        libcalamares.utils.debug("could not size build cores: {}".format(e))

    if build_cores:
        cfg += cfgnixlowram
        catenate(variables, "buildcores", str(build_cores))

    # seat management + device manager: eudev + elogind when Plasma is
    # selected (KWin has no seatd backend, and elogind's TakeDevice needs
    # the udev database), otherwise the Finix default mdevd + seatd.
    # Never both.
    cfg += cfgelogind if needs["elogind"] else cfgseatd

    # networking: dhcpcd + iwd for every selection (NetworkManager is broken
    # under mdevd — no udev database, all devices "unmanaged").
    cfg += cfgnetfinix
    cfg += cfgnetwork

    # Hostname: apply what the user typed on the users page; default "finix"
    # (never "nixos" — the installed system is Finix).
    if gs.value("hostname"):
        catenate(variables, "hostname", gs.value("hostname"))
    else:
        catenate(variables, "hostname", "finix")

    if gs.value("locationRegion") is not None and gs.value("locationZone") is not None:
        cfg += cfgtime
        catenate(
            variables,
            "timezone",
            gs.value("locationRegion"),
            "/",
            gs.value("locationZone"),
        )

    if gs.value("localeConf") is not None:
        localeconf = gs.value("localeConf")
        locale = localeconf.pop("LANG").split("/")[0]
        cfg += cfglocale
        catenate(variables, "LANG", locale)
        if (
            len(set(localeconf.values())) != 1
            or list(set(localeconf.values()))[0] != locale
        ):
            cfg += cfglocaleextra
            for conf in localeconf:
                catenate(variables, conf, localeconf.get(conf).split("/")[0])

    # Login greeter: greetd/tuigreet for every graphical selection (with the
    # xsessions list added when an X11 session — nvwm — is installed);
    # nothing at all for a console-only (minimal) install.
    if needs["console_only"]:
        cfg += cfggreetnone
    elif needs["nvwm"] or needs["vxwm"]:
        cfg += cfggreettuix11
    else:
        cfg += cfggreettui

    # Audio stack (PipeWire), needed by Noctalia / Plasma / NVWM selections.
    if needs["audio"]:
        cfg += cfgaudio

    # Desktop / compositor: emit each selected session's options, deduplicated
    # (e.g. labwc + labwc-noctalia both enable programs.labwc — Nix forbids
    # defining the same attribute twice in one attrset).
    session_opts = []
    for s in selected:
        cfg += "  # --- {} ---\n".format(cfgsessions[s]["comment"])
        for opt in cfgsessions[s]["opts"]:
            if opt not in session_opts:
                session_opts.append(opt)
                cfg += "  {} = true;\n".format(opt)
        cfg += "\n"

    if (
        gs.value("keyboardLayout") is not None
        and gs.value("keyboardVariant") is not None
    ):
        cfg += cfgkeymap
        catenate(variables, "kblayout", gs.value("keyboardLayout"))
        catenate(variables, "kbvariant", gs.value("keyboardVariant"))

        if gs.value("keyboardVConsoleKeymap") is not None:
            try:
                subprocess.check_output(
                    ["pkexec", "loadkeys", gs.value("keyboardVConsoleKeymap").strip()],
                    stderr=subprocess.STDOUT,
                )
                cfg += cfgconsole
                catenate(
                    variables, "vconsole", gs.value("keyboardVConsoleKeymap").strip()
                )
            except subprocess.CalledProcessError as e:
                libcalamares.utils.error("loadkeys: {}".format(e.output))
                libcalamares.utils.error(
                    "Setting vconsole keymap to {} will fail, using default".format(
                        gs.value("keyboardVConsoleKeymap").strip()
                    )
                )
        else:
            kbdmodelmap = open(
                "/run/current-system/sw/share/systemd/kbd-model-map", "r"
            )
            kbd = kbdmodelmap.readlines()
            out = []
            for line in kbd:
                if line.startswith("#"):
                    continue
                out.append(line.split())
            # Find rows with same layout
            find = []
            for row in out:
                if gs.value("keyboardLayout") == row[1]:
                    find.append(row)
            if find != []:
                vconsole = find[0][0]
            else:
                vconsole = ""
            if gs.value("keyboardVariant") is not None:
                variant = gs.value("keyboardVariant")
            else:
                variant = "-"
            # Find rows with same variant
            for row in find:
                if variant in row[3]:
                    vconsole = row[0]
                    break
                # If none found set to "us"
            if vconsole != "" and vconsole != "us" and vconsole is not None:
                try:
                    subprocess.check_output(
                        ["pkexec", "loadkeys", vconsole], stderr=subprocess.STDOUT
                    )
                    cfg += cfgconsole
                    catenate(variables, "vconsole", vconsole)
                except subprocess.CalledProcessError as e:
                    libcalamares.utils.error("loadkeys: {}".format(e.output))
                    libcalamares.utils.error("vconsole value: {}".format(vconsole))
                    libcalamares.utils.error(
                        "Setting vconsole keymap to {} will fail, using default".format(
                            gs.value("keyboardVConsoleKeymap")
                        )
                    )

    if (
        gs.value("packagechooser_packagechooser") is not None
        and gs.value("packagechooser_packagechooser") != ""
    ):
        cfg += cfgmisc

    if gs.value("username") is not None:
        fullname = gs.value("fullname")
        # Finix-safe groups: 'wheel' = sudo, 'video' = GPU access, plus the
        # seatd group for the Wayland seat. 'audio' / 'networkmanager' only
        # when the matching stack is enabled (their groups exist only then).
        groups = ["wheel", "video"]
        if needs["audio"]:
            groups.append("audio")
        if needs["nm"]:
            groups.append("networkmanager")

        cfg += cfgusers
        catenate(variables, "username", gs.value("username"))
        catenate(variables, "fullname", fullname)
        # The seatd group only exists when seatd is the seat manager; under
        # elogind (Plasma) device access comes from logind ACLs instead.
        groups_nix = (" ").join(['"' + s + '"' for s in groups])
        if not needs["elogind"]:
            groups_nix += " config.services.seatd.group"
        catenate(variables, "groups", groups_nix)
        if (
            gs.value("autoLoginUser") is not None
            and gs.value("packagechooser_packagechooser") is not None
            and gs.value("packagechooser_packagechooser") != ""
        ):
            cfg += cfgautologin
            if gs.value("packagechooser_packagechooser") == "gnome":
                cfg += cfgautologingdm
        elif gs.value("autoLoginUser") is not None:
            cfg += cfgautologintty

    # Check if unfree packages are allowed
    free = True
    if gs.value("nixos_allow_unfree"):
        free = False
        cfg += cfgunfree

    cfg += cfgpkgs
    catenate(variables, "pkgs", "")

    cfg += cfgtail

    # Check that all variables are used
    for key in variables.keys():
        pattern = "@@{key}@@".format(key=key)
        if pattern not in cfg:
            libcalamares.utils.warning("Variable '{key}' is not used.".format(key=key))

    # Check that all patterns exist
    variable_pattern = re.compile(r"@@\w+@@")
    for match in variable_pattern.finditer(cfg):
        variable_name = cfg[match.start() + 2 : match.end() - 2]
        if variable_name not in variables:
            libcalamares.utils.warning(
                "Variable '{key}' is used but not defined.".format(key=variable_name)
            )

    # Do the substitutions
    for key in variables.keys():
        pattern = "@@{key}@@".format(key=key)
        cfg = cfg.replace(pattern, str(variables[key]))

    status = _("Generating Finix configuration")
    libcalamares.job.setprogress(0.05)

    try:
        # Generate hardware.nix with mounted swap device
        subprocess.check_output(
            ["pkexec", "nixos-generate-config", "--root", root_mount_point],
            stderr=subprocess.STDOUT,
        )
    except subprocess.CalledProcessError as e:
        if e.output is not None:
            libcalamares.utils.error(e.output.decode("utf8"))
        return (_("nixos-generate-config failed"), _(e.output.decode("utf8")))

    # nixos-generate-config writes into /etc/nixos; relocate its output to
    # /etc/finix and drop the /etc/nixos directory entirely.
    libcalamares.utils.host_env_process_output(
        ["mkdir", "-p", root_mount_point + "/etc/finix"], None
    )
    libcalamares.utils.host_env_process_output(
        [
            "mv",
            root_mount_point + "/etc/nixos/hardware-configuration.nix",
            root_mount_point + "/etc/finix/hardware-configuration.nix",
        ],
        None,
    )
    libcalamares.utils.host_env_process_output(
        ["rm", "-rf", root_mount_point + "/etc/nixos"], None
    )

    # Read and fix hardware-configuration.nix
    hf = open(root_mount_point + "/etc/finix/hardware-configuration.nix", "r")
    htxt = hf.read()
    hf.close()

    hardware_modified = False

    # Strip NixOS-only options that Finix's module set doesn't define
    # (not-detected.nix import -> hardware.enableRedistributableFirmware,
    # hardware.cpu.*.updateMicrocode, networking.useDHCP, nixpkgs.hostPlatform,
    # ...) and inject hardware.firmware. Without this nixos-install aborts with
    # e.g. "The option 'hardware.enableRedistributableFirmware' does not exist".
    try:
        htxt_finix = finixify_hardware_config(htxt)
        if htxt_finix != htxt:
            htxt = htxt_finix
            hardware_modified = True
    except Exception as e:
        libcalamares.utils.warning(
            "finixify_hardware_config failed, using raw nixos-generate-config "
            "output (install may fail on NixOS-only options): {}".format(e)
        )

    # Fix btrfs subvolume configuration if needed
    htxt_fixed = fix_btrfs_subvolumes(htxt, gs.value("partitions"))
    if htxt_fixed != htxt:
        htxt = htxt_fixed
        hardware_modified = True

    # Check for unfree stuff in hardware-configuration.nix
    search = re.search(r"boot\.extraModulePackages = \[ (.*) \];", htxt)

    # Check if any extraModulePackages are defined, and remove if only free packages are allowed
    if search is not None and free:
        expkgs = search.group(1).split(" ")
        for pkg in expkgs:
            p = ".".join(pkg.split(".")[3:])
            # Check package p is unfree
            isunfree = subprocess.check_output(
                [
                    "nix-instantiate",
                    "--eval",
                    "--strict",
                    "-E",
                    "with import <nixpkgs> {{}}; pkgs.linuxKernel.packageAliases.linux_default.{}.meta.unfree".format(
                        p
                    ),
                    "--json",
                ],
                stderr=subprocess.STDOUT,
            )
            if isunfree == b"true":
                libcalamares.utils.warning(
                    "{} is marked as unfree, removing from hardware-configuration.nix".format(
                        p
                    )
                )
                expkgs.remove(pkg)
        htxt = re.sub(
            r"boot\.extraModulePackages = \[ (.*) \];",
            "boot.extraModulePackages = [ {}];".format(
                "".join(map(lambda x: x + " ", expkgs))
            ),
            htxt,
        )
        hardware_modified = True

    # Write the hardware-configuration.nix file if modified
    if hardware_modified:
        libcalamares.utils.host_env_process_output(
            [
                "cp",
                "/dev/stdin",
                root_mount_point + "/etc/finix/hardware-configuration.nix",
            ],
            None,
            htxt,
        )

    # Write the configuration.nix file
    libcalamares.utils.host_env_process_output(["cp", "/dev/stdin", config], None, cfg)

    # Write the flake.nix that makes the installed system a Finix system (finit PID 1).
    flakepath = os.path.join(root_mount_point, "etc/finix/flake.nix")
    libcalamares.utils.host_env_process_output(
        ["cp", "/dev/stdin", flakepath], None, build_flake(needs)
    )

    # Write sessions.nix (always imported by the flake; may be a no-op module).
    sessionspath = os.path.join(root_mount_point, "etc/finix/sessions.nix")
    libcalamares.utils.host_env_process_output(
        ["cp", "/dev/stdin", sessionspath], None, build_sessions_nix(needs)
    )

    # Write branding.nix (always imported: Finix-labelled limine boot menu).
    brandingpath = os.path.join(root_mount_point, "etc/finix/branding.nix")
    libcalamares.utils.host_env_process_output(
        ["cp", "/dev/stdin", brandingpath], None, BRANDING_NIX
    )

    # Write the vendored Plasma module only when the plasma session was
    # selected (the flake imports it conditionally too).
    if needs["plasma"]:
        plasmapath = os.path.join(root_mount_point, "etc/finix/plasma.nix")
        libcalamares.utils.host_env_process_output(
            ["cp", "/dev/stdin", plasmapath], None, PLASMA_NIX
        )

    # Turn the generated /etc/finix into a git repository before running
    # `nixos-install --flake`. Reason: on a plain (non-git) path flake, Nix
    # hashes the directory, then writes flake.lock into it while resolving the
    # finix + nixpkgs inputs; that mutates the directory and invalidates the
    # pinned hash, producing "error: NAR hash mismatch in input 'path:...'".
    # A git-tree flake is hashed from the committed tree, so the later
    # flake.lock write (untracked) no longer perturbs the source hash.
    nixosDir = os.path.join(root_mount_point, "etc/finix")
    try:
        subprocess.check_output(["git", "init", "-q", nixosDir], stderr=subprocess.STDOUT)
        subprocess.check_output(["git", "-C", nixosDir, "add", "-A"], stderr=subprocess.STDOUT)
        subprocess.check_output(
            [
                "git", "-C", nixosDir,
                "-c", "user.email=installer@finix.local",
                "-c", "user.name=Finix Installer",
                "commit", "-q", "-m", "Finix generated system configuration",
            ],
            stderr=subprocess.STDOUT,
        )
    except subprocess.CalledProcessError as e:
        libcalamares.utils.warning(
            "git init of {} failed (flake install may hit a NAR hash mismatch): {}".format(
                nixosDir, e.output
            )
        )

    status = _("Installing Finix")
    libcalamares.job.setprogress(INSTALL_PROGRESS_START)

    try:
        subprocess.check_output(
            ["pkexec", "chmod", "755", root_mount_point],
            stderr=subprocess.STDOUT,
        )
    except subprocess.CalledProcessError as e:
        libcalamares.utils.warning("Failed to set permissions on {}: {}".format(root_mount_point, e.output))

    # Activate the target's swap partition(s) for the duration of the install:
    # the live ISO has no swap, and heavy source builds (noctalia, niri) can
    # otherwise stall the whole machine on low-RAM systems.
    for part in gs.value("partitions"):
        if part.get("fs") == "linuxswap" and part.get("device"):
            try:
                subprocess.check_output(
                    ["pkexec", "swapon", part["device"]],
                    stderr=subprocess.STDOUT,
                )
                libcalamares.utils.debug(
                    "enabled swap on {} for the install".format(part["device"])
                )
            except subprocess.CalledProcessError as e:
                # already on / not formatted yet / zram-only setups: harmless
                libcalamares.utils.debug(
                    "swapon {} skipped: {}".format(part.get("device"), e.output)
                )

    # Nix requires its build directory to have no world-writable parent
    # directories, which rules out anything under /tmp (where Calamares
    # mounts the target). /nix/var/nix/builds satisfies the check BUT on the
    # live ISO it sits on the RAM-backed store overlay — large source builds
    # (niri's cargo target dir, noctalia, wlroots rebuilds) can fill it up,
    # and the kernel then OOM-kills `nix build`.
    # Fix: bind-mount a scratch dir on the TARGET DISK over
    # /nix/var/nix/builds — path keeps its safe parents, data lands on disk.
    build_scratch = os.path.join(root_mount_point, "var/tmp/finix-installer-build")
    build_dir_bound = False
    try:
        subprocess.check_output(
            ["pkexec", "mkdir", "-p", build_scratch, "/nix/var/nix/builds"],
            stderr=subprocess.STDOUT,
        )
        subprocess.check_output(
            ["pkexec", "mount", "--bind", build_scratch, "/nix/var/nix/builds"],
            stderr=subprocess.STDOUT,
        )
        build_dir_bound = True
    except subprocess.CalledProcessError as e:
        libcalamares.utils.warning(
            "could not bind-mount the build dir onto the target disk "
            "(large source builds may exhaust the live RAM): {}".format(e.output)
        )

    # build nixos-install command
    nixosInstallCmd = [ "pkexec" ]
    nixosInstallCmd.extend(generateProxyStrings())
    nixosInstallCmd.extend(
        [
            "nixos-install",
            "--no-root-passwd",
            "--root",
            root_mount_point,
            # Build the installed system from the generated Finix flake (finit PID 1),
            # not a stock NixOS configuration.nix.
            "--flake",
            os.path.join(root_mount_point, "etc/finix") + "#finixos",
            # Serialize derivation builds: with many sessions selected,
            # several large from-source builds (wlroots, niri, noctalia)
            # would otherwise run at once and exhaust memory on small
            # machines. Each build still uses every core.
            "--max-jobs",
            "1",
        ]
    )
    if build_cores:
        nixosInstallCmd.extend(["--cores", str(build_cores)])
    nixosInstallCmd.extend(
        [
            "--option",
            "experimental-features",
            "nix-command flakes",
            "--log-format",
            "internal-json",
            "--option",
            "build-dir",
            "/nix/var/nix/builds",
        ]
    )

    progress = NixProgress()

    try:
        output = ""
        proc = subprocess.Popen(
            nixosInstallCmd,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT
        )
        while True:
            line = proc.stdout.readline().decode("utf-8")
            if not line:
                break

            was_json = progress.handle(line)

            # Keep output for error reporting
            if not was_json:
                output += line
            for log_line in progress.log_messages:
                output += log_line + "\n"

            mapped = INSTALL_PROGRESS_START + progress.fraction * (
                INSTALL_PROGRESS_END - INSTALL_PROGRESS_START
            )
            libcalamares.job.setprogress(mapped)

            for log_line in progress.log_messages:
                libcalamares.utils.debug("nixos-install: {}".format(log_line))
            progress.log_messages.clear()

            if not was_json:
                libcalamares.utils.debug("nixos-install: {}".format(line.strip()))

        exit = proc.wait()
        if exit != 0:
            return (_("Finix installation failed"), _(output))
    except:
        return (_("Finix installation failed"), _("Installation failed to complete"))
    finally:
        # Undo the build-dir bind mount and drop its scratch data from the
        # target disk (also frees the space on the installed system). Must
        # happen on every path or Calamares' umount job would find the
        # target busy.
        if build_dir_bound:
            try:
                subprocess.check_output(
                    ["pkexec", "umount", "/nix/var/nix/builds"],
                    stderr=subprocess.STDOUT,
                )
                subprocess.check_output(
                    ["pkexec", "rm", "-rf", build_scratch],
                    stderr=subprocess.STDOUT,
                )
            except subprocess.CalledProcessError as e:
                libcalamares.utils.warning(
                    "build-dir cleanup failed: {}".format(e.output)
                )

    libcalamares.job.setprogress(INSTALL_PROGRESS_END)
    return None
