def parse_desktop_selection(raw_choice, warn=None):
    """Parse the (comma-separated, multi-select) packagechooser value into a
    validated selection list plus the aggregated feature flags. Anything
    unknown is dropped with a warning; an empty result falls back to the
    default so the install never emits options that don't exist on Finix."""
    if warn is None:
        warn = lambda msg: None
    selected = []
    for choice in raw_choice.split(","):
        choice = choice.strip()
        if not choice:
            continue
        if choice not in cfgsessions:
            warn("Unknown desktop choice '{}', skipping".format(choice))
            continue
        if choice not in selected:
            selected.append(choice)
    if not selected:
        warn(
            "No (valid) desktop selected, falling back to {}".format(
                cfgsessiondefault
            )
        )
        selected = [cfgsessiondefault]

    needs = {
        "console_only": all(cfgsessions[s].get("console") for s in selected),
        "elogind": any(cfgsessions[s].get("elogind") for s in selected),
        "audio": any(cfgsessions[s].get("audio") for s in selected),
        "sddm": any(cfgsessions[s].get("sddm") for s in selected),
        "nm": any(cfgsessions[s].get("nm") for s in selected),
        "plasma": any(cfgsessions[s].get("plasma") for s in selected),
        "nvwm": any(cfgsessions[s].get("nvwm") for s in selected),
        "vxwm": any(cfgsessions[s].get("vxwm") for s in selected),
        "newm": any(cfgsessions[s].get("newm") for s in selected),
        "mango": any(cfgsessions[s].get("mango") for s in selected),
        # Per-compositor flags for the default-config emission (keybinds +
        # launcher; see build_sessions_nix). lxqt runs on labwc too.
        "labwc": any(s in ("labwc", "labwc-noctalia", "lxqt") for s in selected),
        "sway": "sway" in selected,
        "niri": any(s in ("niri", "niri-noctalia") for s in selected),
        "noctalia": any(cfgsessions[s].get("noctalia") for s in selected),
        "noctalia_compositors": [
            cfgsessions[s]["noctalia"]
            for s in selected
            if cfgsessions[s].get("noctalia")
        ],
    }
    return selected, needs


def build_flake(needs):
    """Render the system flake for the selected sessions. Extra inputs
    (noctalia, nvwm sources) and the vendored plasma module are only wired
    in when the matching session was selected."""
    extra_inputs = ""
    if needs["noctalia"]:
        extra_inputs += (
            '    noctalia-src = {\n'
            '      url = "github:noctalia-dev/noctalia-shell/' + NOCTALIA_REV + '";\n'
            '      flake = false;\n'
            '    };\n'
        )
